MEMBER = re.compile(r"^  (\w+)(\??): (.+)$", re.MULTILINE)


def ids_by_kind() -> dict:
    """{kind: [pk, ...]} ascending: a ref's rank is its position, counted from 1,
    which on a first load is its id."""
    return {
        kind: list(model.objects.order_by("pk").values_list("pk", flat=True))
        for kind, model in KINDS.items()
    }


def real(text, ids) -> str:
    """A fixture's first-load refs as this database numbers them."""
    return REF.sub(lambda m: f"{m[1]}:{ids[m[1]][int(m[2]) - 1]}", text)


def first_load(value, ids):
    """A parsed body with every ref rewritten to its first-load rank, wherever it
    stands in a string. A ref naming a row no table holds raises."""
    if isinstance(value, str):
        return REF.sub(lambda m: f"{m[1]}:{ids[m[1]].index(int(m[2])) + 1}", value)
    if isinstance(value, list):
        return [first_load(item, ids) for item in value]
    if isinstance(value, dict):
        return {key: first_load(item, ids) for key, item in value.items()}
    return value


def ask(client, entry, ids) -> tuple:
    """(status, body), a 200's body rewritten to first-load refs. A refusal's
    sentence may name an example ref, and these name no row."""
    query = urlencode(
        [(name, real(value, ids)) for name, value in entry.query], safe=":,"
    )
    path = real(entry.path, ids)
    response = client.get(f"{path}?{query}" if query else path)
    body = response.json()
    if response.status_code == 200:
        body = first_load(body, ids)
    return response.status_code, body


def marked_json(path) -> dict:
    """{marker: the parsed JSON between its markers} of a file."""
    return {
        found["name"]: json.loads(found["json"])
        for found in MARKED.finditer(path.read_text(encoding="utf-8"))
    }


def camel(name) -> str:
    return re.sub(r"-(\w)", lambda m: m[1].upper(), name)


def render(entries, answers) -> str:
    """One generated file, for the entries of one route group."""
    types = ", ".join(sorted({entry.body_type for entry in entries}))
    parts = [
        HEADER,
        f"import type {{ {types} }} from '../../../features/graph/types'\n",
        "import type { RecordedEntry } from './recorded'\n",
    ]
    for entry in entries:
        status, body = answers[entry.name]
        record = {
            "name": entry.name,
            "caller": entry.caller,
            "path": entry.path,
            "query": [list(pair) for pair in entry.query],
            "status": status,
            "body": body,
        }
        text = json.dumps(record, indent=2, ensure_ascii=True)
        parts.append(
            f"\nexport const {camel(entry.name)}: RecordedEntry<{entry.body_type}> =\n"
            f"// <<< {entry.name}\n{text}\n// >>> {entry.name}\n"
        )
    return "".join(parts)


def test_a_ref_becomes_its_rank_wherever_it_stands():
    ids = {
        "entity": [101, 205],
        "relationship": [310],
        "release": [7],
        "evidence": [900],
    }
    body = {
        "id": "entity:205",
        "edge": "relationship:310",
        "next": "evidence:900",
        "detail": "entity:101: more than 200",
        "keep": "MI:0407",
        "releases": ["release:7"],
    }
    assert first_load(body, ids) == {
        "id": "entity:2",
        "edge": "relationship:1",
        "next": "evidence:1",
        "detail": "entity:1: more than 200",
        "keep": "MI:0407",
        "releases": ["release:1"],
    }
    assert real("entities/entity:2", ids) == "entities/entity:205"
    assert real("relationships/relationship:1", ids) == "relationships/relationship:310"
    with pytest.raises(ValueError):
        first_load("evidence:901", ids)


def test_ask_numbers_a_request_and_a_200_by_rank():
    # On a fresh database every id is its rank, so the comparison cannot see this.
    ids = {"entity": [101], "relationship": [310], "release": [7], "evidence": []}
    entry = e("x", "x", "X", "relationships/relationship:1", ("releases", "release:1"))
    client = mock.Mock()
    client.get.return_value.status_code = 200
    client.get.return_value.json.return_value = {
        "id": "relationship:310",
        "source": "entity:101",
    }
    assert ask(client, entry, ids) == (
        200,
        {"id": "relationship:1", "source": "entity:1"},
    )
    client.get.assert_called_once_with(
        "relationships/relationship:310?releases=release:7"
    )


def test_each_recorded_fixture_is_the_apis_response(demo, settings):
    ids = ids_by_kind()
    clients = {"staff": demo.staff, "visitor": APIClient(), "off": APIClient()}
    answers = {}
    for entry in ENTRIES:
        settings.TYPED_GRAPH_ENABLED = entry.caller != "off"
        answers[entry.name] = ask(clients[entry.caller], entry, ids)
    if WRITE_TO:
        # jsonb sorts record.raw's keys; SQLite would write another order.
        assert connection.vendor == "postgresql", "regenerate on PostgreSQL"
        for name in {entry.file for entry in ENTRIES}:
            group = [entry for entry in ENTRIES if entry.file == name]
            (Path(WRITE_TO) / f"{name}.ts").write_text(
                render(group, answers), encoding="utf-8", newline="\n"
            )
        pytest.skip(f"wrote the fixtures to {WRITE_TO}: review the diff and rerun")
    saved = {}
    for name in {entry.file for entry in ENTRIES}:
        path = FIXTURES / f"{name}.ts"
        assert path.read_text(encoding="utf-8").startswith(HEADER), path.name
        saved.update(marked_json(path))
    assert set(saved) == set(answers), "ENTRIES and the fixture files differ"
    wrong = [
        entry.name
        for entry in ENTRIES
        if (saved[entry.name]["caller"], saved[entry.name]["path"])
        != (entry.caller, entry.path)
        or saved[entry.name]["query"] != [list(pair) for pair in entry.query]
        or (saved[entry.name]["status"], saved[entry.name]["body"])
        != answers[entry.name]
    ]
    assert not wrong, (
        f"these fixtures are no longer the API's answers: {wrong}. "
        "Regenerate them (this file's docstring), and review the diff."
    )


def test_each_handler_mirrors_its_view():
    [routes] = marked_json(HANDLERS).values()
    assert {route["path"]: route["allowed"] for route in routes} == {
        path: list(view.allowed_params)
        for method, path, view in typed_routes()
        if method == "GET"
    }


def declared_interfaces(text) -> dict:
    """{interface: [(key, "?" or "", type text), ...]}, every extends flattened."""
    heads = {}
    for found in INTERFACE.finditer(text):
        name, _, bases = re.sub(r"<[^<>]*>", "", found["head"]).partition(" extends ")
        heads[name.strip()] = (
            [base.strip() for base in bases.split(",") if base.strip()],
            MEMBER.findall(found["body"]),
        )

    def members(name):
        bases, own = heads[name]
        return [member for base in bases for member in members(base)] + own

    return {name: members(name) for name in heads}


def test_each_type_states_its_serializers_keys_and_nulls():
    text = TYPES.read_text(encoding="utf-8")
    declared = declared_interfaces(text)
    classes = {
        name: value
        for module in (graph_serializers, browser_serializers)
        for name, value in vars(module).items()
        if name.endswith("Serializer")
        and getattr(value, "__module__", "") == module.__name__
    }
    assert set(classes) - {"FeaturesSerializer"} == {
        serializer for _, serializer in TYPE_SERIALIZERS
    }, "a serializer has no type, or a type names no serializer"
    wrong = {}
    for interface, serializer in TYPE_SERIALIZERS:
        fields = classes[serializer]().fields
        members = declared[interface]
        required = {key for key, optional, _ in members if not optional}
        nullable = {key for key, _, kind in members if kind.endswith("| null")}
        allowed = {key for key, field in fields.items() if field.allow_null}
        if required != set(fields) or nullable != allowed:
            wrong[interface] = {
                "keys": sorted(required ^ set(fields)),
                "nulls": sorted(nullable ^ allowed),
            }
    assert not wrong, f"types.ts differs from the serializers: {wrong}"
    union = re.search(r"export type GraphFeatureName =\s*((?:\|?\s*'\w+'\s*)+)", text)
    assert set(re.findall(r"'(\w+)'", union[1])) == set(
        classes["FeaturesSerializer"]().fields
    )


